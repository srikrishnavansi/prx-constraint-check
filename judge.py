"""Judge the 40 PRX images twice (k=2) with Claude vision, plus a pixel check of background whiteness. Needs ANTHROPIC_API_KEY in the environment."""
import base64, json, os, sys, collections
from concurrent.futures import ThreadPoolExecutor
import numpy as np
from PIL import Image
os.chdir(os.path.dirname(os.path.abspath(__file__)))
import llm as em
from prompts import CASES
PACK, MODEL = 'prx-constraint-check', 'claude-haiku-5-5'
WHITE_MIN, BORDER_FRAC, PASS_AT = 235, 0.06, 0.90  # calibration knobs: pixel counts as white if min(R,G,B) >= 235

def white_border(path):
    a = np.asarray(Image.open(path).convert('RGB')).astype(int); h, w, _ = a.shape; b = int(h * BORDER_FRAC)
    edge = np.concatenate([a[:b].reshape(-1, 3), a[-b:].reshape(-1, 3), a[:, :b].reshape(-1, 3), a[:, -b:].reshape(-1, 3)])
    frac = float((edge.min(1) >= WHITE_MIN).mean()); return round(frac, 3), frac >= PASS_AT

SYS = ("You check product photos generated by a text-to-image model against one constraint. Look carefully; count objects one by one. "
       "Be strict: a constraint is met only if it is clearly and fully met in the image.")
SCHEMA = {"type": "object", "additionalProperties": False, "required": ["observed", "constraint_met", "white_background", "any_text_visible"],
          "properties": {"observed": {"type": "string", "description": "one short sentence: what you see that decides the constraint, e.g. counts"},
                         "constraint_met": {"type": "boolean"}, "white_background": {"type": "boolean", "description": "background is plain pure white"},
                         "any_text_visible": {"type": "boolean", "description": "any letters, numbers, logos or label text visible anywhere"}}}

def judge(c):
    b64 = base64.b64encode(open(f"img/{c['id']}.png", 'rb').read()).decode()
    user = [{"type": "image", "source": {"type": "base64", "media_type": "image/png", "data": b64}},
            {"type": "text", "text": f"Prompt given to the model: {c['prompt']}\nConstraint to check: {c['constraint']}"}]
    for a in range(4):
        try: return em.call(PACK, f"{MODEL} judge", MODEL, SYS, user, schema=SCHEMA, max_tokens=600, effort='low')
        except Exception as e:
            if a == 3 or isinstance(e, SystemExit): raise

if __name__ == '__main__':
    px = {c['id']: white_border(f"img/{c['id']}.png") for c in CASES}
    runs = []
    for k in (1, 2):
        with ThreadPoolExecutor(6) as ex: runs.append(dict(zip([c['id'] for c in CASES], ex.map(judge, CASES))))
    rows = [{**c, 'px_white_frac': px[c['id']][0], 'px_white': px[c['id']][1], 'j1': runs[0][c['id']], 'j2': runs[1][c['id']]} for c in CASES]
    by = collections.defaultdict(lambda: [0, 0, 0, 0])  # pass run1, pass run2, agree, n
    for r in rows:
        t = by[r['type']]; t[0] += r['j1']['constraint_met']; t[1] += r['j2']['constraint_met']; t[2] += r['j1']['constraint_met'] == r['j2']['constraint_met']; t[3] += 1
    S = {'per_type': {k: dict(zip(['pass_run1', 'pass_run2', 'agree', 'n'], v)) for k, v in by.items()},
         'pass_run1': sum(r['j1']['constraint_met'] for r in rows), 'pass_run2': sum(r['j2']['constraint_met'] for r in rows),
         'judge_agree_k2': sum(r['j1']['constraint_met'] == r['j2']['constraint_met'] for r in rows),
         'pass_both_runs': sum(r['j1']['constraint_met'] and r['j2']['constraint_met'] for r in rows),
         'px_white_pass': sum(r['px_white'] for r in rows),
         'judge_white_run1': sum(r['j1']['white_background'] for r in rows),
         'judge_vs_pixel_white_agree_run1': sum(r['j1']['white_background'] == r['px_white'] for r in rows),
         'notext_with_text_seen_run1': sum(r['j1']['any_text_visible'] for r in rows if r['type'] == 'no_text'),
         'usd_pack_total': round(em.spent(PACK), 4)}
    json.dump({'judge': MODEL, 'summary': S, 'rows': rows}, open('results.json', 'w'), indent=1)
    print(json.dumps(S, indent=1))
    for r in rows: print(r['id'], 'P' if r['j1']['constraint_met'] else 'F', 'P' if r['j2']['constraint_met'] else 'F', r['px_white_frac'], '|', r['j1']['observed'][:110])
